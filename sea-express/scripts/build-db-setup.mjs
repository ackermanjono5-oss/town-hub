/**
 * Builds supabase/setup/full_setup.sql: one script that sets up a Town Hub
 * database from scratch, for pasting into the Supabase SQL Editor.
 *
 *   1. Removes the tables, functions and sign-up trigger left by an earlier
 *      version of the app — but refuses to run if they hold any rows.
 *   2. Applies every migration in supabase/migrations, in order.
 *   3. Adds redemption_tokens to Realtime, so a customer's voucher flips to
 *      "Redeemed" on their phone the moment staff confirm it.
 *
 * It all runs in one transaction: any error rolls everything back.
 *
 * Run:  node scripts/build-db-setup.mjs
 */

import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = join(ROOT, 'supabase', 'migrations');
const OUT_DIR = join(ROOT, 'supabase', 'setup');
const OUT_FILE = join(OUT_DIR, 'full_setup.sql');

const RESET = `-- ---------------------------------------------------------------------
-- Part 1: remove the earlier app version's schema
-- ---------------------------------------------------------------------
-- Stops here, changing nothing, if any of these tables or auth.users holds
-- a row — this part is only for a database with no real data in it.
do $$
declare
  t text;
  n bigint;
begin
  foreach t in array array[
    'public.profiles', 'public.businesses', 'public.offers', 'public.redemption_tokens',
    'public.redemptions', 'public.employees', 'public.legal_notices', 'public.wall_posts',
    'auth.users'
  ] loop
    if to_regclass(t) is not null then
      execute format('select count(*) from %s', t) into n;
      if n > 0 then
        raise exception 'Setup stopped: % has % row(s). This script only resets an empty database.', t, n;
      end if;
    end if;
  end loop;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

drop table if exists
  public.wall_reports,
  public.wall_posts,
  public.redemptions,
  public.redemption_tokens,
  public.offers,
  public.branches,
  public.employees,
  public.business_registration_codes,
  public.legal_notices,
  public.businesses,
  public.profiles
  cascade;

drop function if exists public.handle_new_user() cascade;
drop function if exists public.set_updated_at() cascade;
drop function if exists public.touch_profile_updated_at() cascade;
drop function if exists public.is_admin() cascade;
drop function if exists public.is_business_member(uuid) cascade;
drop function if exists public.register_business_with_code(text, uuid) cascade;
drop function if exists public.handle_new_business_owner() cascade;

drop type if exists public.profile_role, public.offer_type, public.token_status cascade;
`;

const REALTIME = `-- ---------------------------------------------------------------------
-- Part 3: live voucher status
-- ---------------------------------------------------------------------
-- QRDisplay subscribes to changes on the customer's voucher row; Supabase
-- only broadcasts tables in the supabase_realtime publication.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (
       select 1 from pg_publication_tables
       where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'redemption_tokens'
     ) then
    alter publication supabase_realtime add table public.redemption_tokens;
  end if;
end;
$$;
`;

const AFTER = `-- ---------------------------------------------------------------------
-- After setup (run separately, once you have signed up in the app)
-- ---------------------------------------------------------------------
-- Make your own account the Town Hub administrator:
--
--   update public.profiles set role = 'admin', is_subscribed = true
--   where id = (select id from auth.users where email = 'you@example.com');
--
-- Switch on a customer's rewards membership:
--
--   update public.profiles set is_subscribed = true
--   where id = (select id from auth.users where email = 'customer@example.com');
`;

const files = readdirSync(MIGRATIONS)
  .filter((f) => /^\d+_.+\.sql$/.test(f))
  .sort();

const parts = files.map((f) => {
  const sql = readFileSync(join(MIGRATIONS, f), 'utf8').replace(/\r\n/g, '\n').trim();
  return `-- =====================================================================\n-- ${f}\n-- =====================================================================\n${sql}\n`;
});

const header = `-- Town Hub — full database setup. GENERATED by scripts/build-db-setup.mjs
-- from supabase/migrations (${files.join(', ')}). Do not edit by hand.
--
-- Paste the whole file into the Supabase SQL Editor and click Run. Runs in
-- one transaction: if anything fails, nothing is changed.
`;

mkdirSync(OUT_DIR, { recursive: true });
writeFileSync(
  OUT_FILE,
  [
    header,
    'begin;\n',
    RESET,
    '-- ---------------------------------------------------------------------\n-- Part 2: migrations\n-- ---------------------------------------------------------------------\n',
    ...parts,
    REALTIME,
    'commit;\n',
    AFTER,
  ].join('\n'),
  'utf8'
);

console.log(`Wrote ${OUT_FILE} from ${files.length} migrations.`);
