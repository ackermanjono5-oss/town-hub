/**
 * Downloads each attorney's own logo for the Attorneys directory.
 *
 * Reads every `website: '...'` in lib/garden-route/attorneys.ts, fetches the
 * icon that firm's site declares (manifest / apple-touch-icon / favicon) and
 * bundles it under public/logos/attorneys/, because the app runs offline from
 * file:// and cannot load remote images. Firms without a usable icon fall
 * back to a monogram tile.
 *
 * Mirrors scripts/fetch-site-logos.mjs.
 *
 * Run:  node scripts/fetch-attorney-logos.mjs
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { fetchBestIcon, mapLimit, slugify } from './lib/icon-fetch.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SOURCE = join(ROOT, 'lib', 'garden-route', 'attorneys.ts');
const OUT_DIR = join(ROOT, 'public', 'logos', 'attorneys');
const OUT_FILE = join(ROOT, 'lib', 'garden-route', 'attorney-logos.ts');

const CONCURRENCY = 6;
const MIN_PX = 48;
const OUT_PX = 128;

async function main() {
  const src = await readFile(SOURCE, 'utf8');
  const domains = new Set();
  for (const m of src.matchAll(/website: '(https?:\/\/[^']+)'/g)) {
    try {
      domains.add(new URL(m[1]).hostname.replace(/^www\./, ''));
    } catch {
      /* malformed URL — skip */
    }
  }
  const list = [...domains].sort();
  console.log(`Trying ${list.length} attorney domains…`);

  await mkdir(OUT_DIR, { recursive: true });

  const found = [];
  let done = 0;
  await mapLimit(list, CONCURRENCY, async (domain) => {
    const result = await fetchBestIcon(domain, { minPx: MIN_PX, outPx: OUT_PX });
    done += 1;
    if (result) {
      const file = `${slugify(domain)}.png`;
      await writeFile(join(OUT_DIR, file), result.png);
      found.push({ domain, file, size: result.size, hash: result.hash });
      console.log(`  [${done}/${list.length}] ok    ${domain}  (${result.size})`);
    } else {
      console.log(`  [${done}/${list.length}] none  ${domain}`);
    }
  });

  found.sort((a, b) => a.domain.localeCompare(b.domain));
  const entries = found
    .map((f) => `  ['${f.domain}', 'logos/attorneys/${f.file}'],`)
    .join('\n');

  await writeFile(
    OUT_FILE,
    `// Generated by scripts/fetch-attorney-logos.mjs — do not edit by hand.
// Each logo was downloaded from that firm's own website (its declared icon)
// and bundled so it works offline. Icons smaller than ${MIN_PX}px were
// skipped; those firms fall back to a monogram tile.
export const ATTORNEY_LOGOS = new Map<string, string>([
${entries}
]);

export function getAttorneyLogo(website: string | undefined): string | undefined {
  if (!website) return undefined;
  try {
    return ATTORNEY_LOGOS.get(new URL(website).hostname.replace(/^www\\./, ''));
  } catch {
    return undefined;
  }
}
`,
    'utf8'
  );

  console.log(`\nResolved ${found.length}/${list.length} domains.`);
  // The same image on unrelated domains is almost always a CMS or platform
  // glyph rather than a firm's logo — check these by eye.
  const byHash = new Map();
  for (const f of found) {
    if (f.hash) byHash.set(f.hash, [...(byHash.get(f.hash) ?? []), f.domain]);
  }
  const shared = [...byHash.entries()].filter(([, d]) => d.length > 1);
  if (shared.length > 0) {
    console.log('\nSame image on multiple domains — check these are real logos:');
    for (const [hash, d] of shared) console.log(`  ${hash}  ${d.join(', ')}`);
  }
  console.log(`Wrote ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
