/**
 * Re-checks every website in lib/garden-route/discovered-sites.ts and drops
 * the ones that cannot be shown to be the right business.
 *
 * Discovery guesses a domain from the listing name, so the weak case is a
 * listing whose name is a single ordinary word — "Handel", "The Foundation",
 * "Glow". Those match an unrelated national company that happens to own the
 * obvious domain, and the result is a stranger's logo on a real local business.
 *
 * The rule here is stricter the less distinctive the name is:
 *   - two or more distinctive words: the region is enough (it was already
 *     verified at discovery time),
 *   - a single distinctive word: the page must name the listing's own town.
 *
 * Run:  node scripts/verify-discovered-sites.mjs
 */

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { mapLimit, USER_AGENT } from './lib/icon-fetch.mjs';
import { TOWNS } from './lib/towns.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const FILE = join(ROOT, 'lib', 'garden-route', 'discovered-sites.ts');

const SOURCES = [
  'lib/garden-route/restaurants.ts',
  'lib/garden-route/businesses.ts',
  'lib/garden-route/accommodation.ts',
  'lib/garden-route/medical-osm.ts',
];

const GENERIC = new Set([
  'the', 'and', 'for', 'shop', 'store', 'cafe', 'restaurant', 'bar', 'pub',
  'hotel', 'guest', 'house', 'lodge', 'inn', 'bed', 'breakfast', 'self',
  'catering', 'accommodation', 'garden', 'route', 'bay', 'street', 'road',
  'centre', 'center', 'group', 'services', 'service', 'company', 'trading',
  'pty', 'ltd', 'south', 'africa', 'african', 'sea', 'beach', 'river',
  'village', 'town', 'market', 'shopping', 'mall', 'plaza', 'point', 'view',
  'new', 'old', 'big', 'little', 'small', 'best', 'home', 'place', 'spot',
  'supermarket', 'pharmacy', 'chemist', 'butcher', 'bakery', 'barber',
  'salon', 'garage', 'hardware', 'liquor', 'bottle', 'deli', 'takeaway',
  'clinic', 'dentist', 'doctor', 'doctors', 'school', 'church', 'office',
  'studio', 'gallery', 'nursery', 'laundry', 'superette', 'grocer',
]);

const TIMEOUT_MS = 8000;

function distinctive(name) {
  return name
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9\s]/g, ' ')
    .split(/\s+/)
    .filter((w) => w.length >= 4 && !GENERIC.has(w));
}

async function fetchBody(url) {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS);
  try {
    const res = await fetch(url, {
      signal: controller.signal,
      redirect: 'follow',
      headers: { 'User-Agent': USER_AGENT, Accept: 'text/html,application/xhtml+xml' },
    });
    if (!res.ok) return null;
    return (await res.text()).slice(0, 150_000).replace(/<[^>]+>/g, ' ').toLowerCase();
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

async function main() {
  const src = await readFile(FILE, 'utf8');
  const rows = [...src.matchAll(/\['(.+?)', '(.+?)'\]/g)].map((m) => ({
    name: m[1].replace(/\\'/g, "'"),
    raw: m[1],
    url: m[2],
  }));

  // Listing name -> town slug, so a single-word name can be held to its town.
  const townOf = new Map();
  for (const file of SOURCES) {
    const text = await readFile(join(ROOT, file), 'utf8');
    for (const m of text.matchAll(/name: '((?:[^'\\]|\\.)*)',([\s\S]*?)\n  \}/g)) {
      const town = /town: '([^']+)'/.exec(m[2])?.[1];
      if (town) townOf.set(m[1].replace(/\\'/g, "'"), town);
    }
  }
  const townLabel = new Map(TOWNS.map((t) => [t.slug, t.label.toLowerCase()]));

  console.log(`Re-verifying ${rows.length} discovered websites…`);
  const keep = [];
  const drop = [];

  await mapLimit(rows, 10, async (row) => {
    const words = distinctive(row.name);
    const body = await fetchBody(row.url);
    if (!body) {
      drop.push({ ...row, why: 'unreachable' });
      return;
    }
    if (words.length >= 2) {
      keep.push(row);
      return;
    }
    // Single distinctive word: demand the town by name.
    const slug = townOf.get(row.name);
    const label = slug ? townLabel.get(slug) : null;
    if (label && body.includes(label)) keep.push(row);
    else drop.push({ ...row, why: `single-word name, page never mentions ${label ?? 'its town'}` });
  });

  keep.sort((a, b) => a.name.localeCompare(b.name));
  const rowsOut = keep.map((k) => `  ['${k.raw}', '${k.url}'],`).join('\n');

  await writeFile(
    FILE,
    `// Generated by scripts/discover-websites.mjs and pruned by
// scripts/verify-discovered-sites.mjs — do not edit by hand.
//
// Websites found by guessing the obvious domain for a listing and then
// verifying the page belongs to that business. A listing named with a single
// ordinary word ("Handel", "The Foundation") must additionally have its own
// town named on the page, because otherwise it matches whichever national
// company happens to own that domain.
//
// Kept separate from the generated import files so re-importing from
// OpenStreetMap never clobbers these, and these never override a website a
// mapper actually recorded.
export const DISCOVERED_SITES = new Map<string, string>([
${rowsOut}
]);
`,
    'utf8'
  );

  console.log(`\nKept ${keep.length}, dropped ${drop.length}:`);
  for (const d of drop.sort((a, b) => a.name.localeCompare(b.name))) {
    console.log(`  ${d.name.padEnd(24)} ${d.url.padEnd(36)} ${d.why}`);
  }
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
