/**
 * Builds single-file copies of each Edge Function for pasting into the
 * Supabase dashboard editor (Edge Functions → Deploy a new function → Via
 * Editor), for when the Supabase CLI isn't available.
 *
 * Each bundle is the function's index.ts with the ../_shared/*.ts modules it
 * imports inlined above it. The CLI deploy (`supabase functions deploy`)
 * remains the normal path; these are generated, never edited.
 *
 * Run:  node scripts/build-function-bundles.mjs
 */

import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FUNCTIONS = join(ROOT, 'supabase', 'functions');
const OUT_DIR = join(ROOT, 'supabase', 'setup', 'dashboard-functions');

const SHARED_IMPORT = /^import\s+\{[^}]*\}\s+from\s+'\.\.\/_shared\/([\w-]+)\.ts';\s*$/gm;
const NPM_IMPORT = /^import\s+.*from\s+'npm:[^']+';\s*$/gm;

mkdirSync(OUT_DIR, { recursive: true });

for (const name of readdirSync(FUNCTIONS)) {
  const entry = join(FUNCTIONS, name, 'index.ts');
  if (name.startsWith('_') || !existsSync(entry)) continue;

  const source = readFileSync(entry, 'utf8').replace(/\r\n/g, '\n');
  const sharedNames = [...source.matchAll(SHARED_IMPORT)].map((m) => m[1]);

  const npmImports = new Set();
  const sharedBlocks = sharedNames.map((shared) => {
    let code = readFileSync(join(FUNCTIONS, '_shared', `${shared}.ts`), 'utf8').replace(/\r\n/g, '\n');
    for (const m of code.matchAll(NPM_IMPORT)) npmImports.add(m[0]);
    code = code.replace(NPM_IMPORT, '').replace(/^export\s+/gm, '').trim();
    return `// ---- inlined from _shared/${shared}.ts ----\n${code}\n`;
  });

  const body = source.replace(SHARED_IMPORT, '').trim();
  const bundle = [
    `// ${name} — GENERATED by scripts/build-function-bundles.mjs from`,
    `// supabase/functions/${name}/index.ts with its _shared modules inlined.`,
    `// For pasting into the Supabase dashboard editor; do not edit by hand.`,
    '',
    ...npmImports,
    '',
    ...sharedBlocks,
    `// ---- ${name}/index.ts ----`,
    body,
    '',
  ].join('\n');

  writeFileSync(join(OUT_DIR, `${name}.ts`), bundle, 'utf8');
  console.log(`Wrote ${name}.ts (${sharedNames.length} shared modules inlined)`);
}
