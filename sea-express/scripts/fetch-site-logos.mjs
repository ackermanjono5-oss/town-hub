/**
 * Downloads a real logo for every Garden Route business that publishes a
 * website, straight from that business's own site.
 *
 * For each distinct domain across the directory data files it reads the
 * homepage, picks the best <link rel="...icon"> it advertises (preferring a
 * large apple-touch-icon over a 16px favicon), downloads it, and writes a
 * square PNG into public/logos/sites/. It then regenerates
 * lib/garden-route/business-logos.ts mapping domain -> asset path.
 *
 * Why not a brand-logo API: the app is bundled into an APK and runs from
 * file://, so every image must ship inside the build. Brandfetch's bulk CDN
 * URLs are hotlink-only and cannot be downloaded programmatically, and a
 * per-brand lookup for 85 independent local businesses is neither available
 * nor worth the round trips. A site's own touch-icon is its real mark, is
 * served by the business itself, and needs no third party.
 *
 * Icons smaller than MIN_PX are skipped: a 16x16 favicon looks like noise at
 * card size, and a monogram tile reads better than a blurry smudge.
 *
 * Run:  node scripts/fetch-business-logos.mjs
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { fetchBestIcon, mapLimit, slugify } from './lib/icon-fetch.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
// Every directory whose listings carry their own website. One domain -> logo
// map serves all of them, so a hotel and a shop on the same domain share an
// asset and nothing is downloaded twice.
const SOURCES = [
  join(ROOT, 'lib', 'garden-route', 'businesses.ts'),
  join(ROOT, 'lib', 'garden-route', 'accommodation.ts'),
  join(ROOT, 'lib', 'garden-route', 'restaurants.ts'),
  // Websites found by scripts/discover-websites.mjs for listings that had
  // none. Same `website: '...'` shape, so it is read the same way.
  join(ROOT, 'lib', 'garden-route', 'discovered-sites.ts'),
];
const OUT_DIR = join(ROOT, 'public', 'logos', 'sites');
const OUT_FILE = join(ROOT, 'lib', 'garden-route', 'site-logos.ts');

const CONCURRENCY = 8;
const TIMEOUT_MS = 8000;
const MIN_PX = 48;
const OUT_PX = 128;

const USER_AGENT =
  'sea-express-garden-route/1.0 (business directory logo fetch; contact via app listing)';

// Hosts that would return a social network's logo rather than the business's.
const SKIP_HOST =
  /facebook|instagram|twitter|linkedin|wixsite|business\.site|blogspot|google\.|airbnb|lekkeslaap|booking\.com|safarinow|nightsbridge|tripadvisor|expedia|agoda/i;

async function main() {
  const domains = new Set();
  for (const source of SOURCES) {
    const src = await readFile(source, 'utf8');
    // Matches any quoted URL, which covers both the `website: '...'` field
    // in the imports and the ['Name', 'https://...'] rows in
    // discovered-sites.ts.
    for (const m of src.matchAll(/'(https?:\/\/[^']+)'/g)) {
      try {
        const host = new URL(m[1]).hostname.replace(/^www\./, '');
        if (!SKIP_HOST.test(host)) domains.add(host);
      } catch {
        /* malformed URL in the import — skip */
      }
    }
  }
  const list = [...domains].sort();
  console.log(`Trying ${list.length} listing domains…`);

  await mkdir(OUT_DIR, { recursive: true });

  const found = [];
  let done = 0;
  await mapLimit(list, CONCURRENCY, async (domain) => {
    const result = await fetchBestIcon(domain, { minPx: MIN_PX, outPx: OUT_PX });
    done += 1;
    if (result) {
      const file = `${slugify(domain)}.png`;
      await writeFile(join(OUT_DIR, file), result.png);
      found.push({ domain, file, size: result.size, hash: result.hash });
      console.log(`  [${done}/${list.length}] ok    ${domain}  (${result.size})`);
    } else {
      console.log(`  [${done}/${list.length}] none  ${domain}`);
    }
  });

  found.sort((a, b) => a.domain.localeCompare(b.domain));
  const entries = found
    .map((f) => `  ['${f.domain}', 'logos/sites/${f.file}'],`)
    .join('\n');

  await writeFile(
    OUT_FILE,
    `// Generated by scripts/fetch-site-logos.mjs — do not edit by hand.
// Each logo was downloaded from that business's own website (its declared
// favicon / apple-touch-icon) and bundled so it works offline. Icons smaller
// than ${MIN_PX}px were skipped; those listings fall back to a monogram tile.
export const SITE_LOGOS = new Map<string, string>([
${entries}
]);
`,
    'utf8'
  );

  console.log(`\nResolved ${found.length}/${list.length} domains.`);
  // The same image on unrelated domains almost always means a third-party
  // glyph rather than a real logo. Reported so a new one can be checked and,
  // if bogus, added to BLOCKED_ICON_HASHES in scripts/lib/icon-fetch.mjs.
  const byHash = new Map();
  for (const f of found) {
    if (f.hash) byHash.set(f.hash, [...(byHash.get(f.hash) ?? []), f.domain]);
  }
  const shared = [...byHash.entries()].filter(([, d]) => d.length > 1);
  if (shared.length > 0) {
    console.log('');
    console.log('Same image on multiple domains — check these are real brands:');
    for (const [hash, d] of shared) console.log(`  ${hash}  ${d.join(', ')}`);
  }

  console.log(`Wrote ${OUT_FILE}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
